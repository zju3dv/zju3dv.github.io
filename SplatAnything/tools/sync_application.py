#!/usr/bin/env python3
"""Sync Application previews from images/application/{rig,pano}/<number>/.

Uses the same poster, thumbnail and preview conventions as sync_gallery.py.
Empty numbered directories remain visible as case slots. Remote HTML is resolved
on demand from the matching rig/<number> or pano/<number> dataset folder.
"""

import json

from sync_gallery import ROOT, scan


def main():
    source = ROOT / "images/application"
    gallery = {
        category: scan(category, source=source, label=label, include_empty=True)
        for category, label in (("pano", "Pano"), ("rig", "Rig"))
    }
    output = ROOT / "assets/js/application.js"
    output.write_text(
        "// Generated by tools/sync_application.py from images/application. Do not edit by hand.\n"
        + "window.SPLAT_APPLICATION = "
        + json.dumps(gallery, indent=2, ensure_ascii=False)
        + ";\n"
    )
    for category, scenes in gallery.items():
        print(f"{category:7s} {len(scenes):3d} cases, {sum(bool(s['preview']) for s in scenes)} preview videos")


if __name__ == "__main__":
    main()
